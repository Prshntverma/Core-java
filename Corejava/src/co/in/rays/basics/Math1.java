package co.in.rays.basics;

public class Math1 {

	public static void main(String[] args) {
		 System.out.println("Mathematics Operation");
		 System.out.println("maximum number is  :"+Math.max(2, 7));
		 System.out.println("minimum number is  :"+Math.min(2, 7));
		 System.out.println("absolute 3.7  :"+Math.abs(-3.7)); //it is providing absolute positive value
		 System.out.println(" Exp 10  :"+Math.exp(2)); //euler rule e^n  if e1 = 2.718
		 System.out.println("random number :"+Math.random()*10);
		 System.out.println("Square root  :" +Math.sqrt(4567));
		 
		 
	}
}
