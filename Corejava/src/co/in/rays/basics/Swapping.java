package co.in.rays.basics;

public class Swapping 
     {

	public static void main(String[] args) {
		int a  = 5;
		int b = 10;
		int c;
		
		System.out.println(a+".....= a");
		System.out.println(b+".....= b");
		
		
		System.out.println(".....Swapping......");
		
		 c=a;
		 a=b;
		 b=c;
		 System.out.println(a+".....= a");
		 System.out.println(b+".....= b");
		 System.out.println(c+".....= c");
		
		
	}
}
